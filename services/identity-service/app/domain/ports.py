"""Segregated domain ports (DIP/ISP) for Identity & Organization service."""
from __future__ import annotations

from datetime import date
from typing import Any, Optional, Protocol

from unisora_kit import RequestContext
from app.domain.entities import (
    DepartmentEntity,
    DepartmentMembershipEntity,
    OrganizationEntity,
    UserEntity,
)


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, plain_password: str, hashed_password: str) -> bool: ...


class TokenIssuer(Protocol):
    def create_access_token(self, payload: dict[str, Any], expires_minutes: int) -> str: ...


class OrganizationRepository(Protocol):
    def get_by_id(self, organization_id: int) -> Optional[OrganizationEntity]: ...
    def create(self, name: str) -> OrganizationEntity: ...
    def save(self, org: OrganizationEntity) -> OrganizationEntity: ...


class UserRepository(Protocol):
    def get_by_id(self, user_id: int) -> Optional[UserEntity]: ...
    def get_by_id_in_org(self, user_id: int, organization_id: int) -> Optional[UserEntity]: ...
    def get_by_email(self, email: str) -> Optional[UserEntity]: ...
    def get_by_email_in_org(self, email: str, organization_id: int) -> Optional[UserEntity]: ...
    def get_by_employee_id_in_org(self, employee_id: str, organization_id: int) -> Optional[UserEntity]: ...
    def list_by_org(self, organization_id: int) -> list[UserEntity]: ...
    def create(self, user: UserEntity) -> UserEntity: ...
    def save(self, user: UserEntity) -> UserEntity: ...


class DepartmentRepository(Protocol):
    def list_by_org(self, organization_id: int) -> list[DepartmentEntity]: ...
    def get_by_id(self, department_id: int, organization_id: int) -> Optional[DepartmentEntity]: ...
    def get_by_name(self, name: str, organization_id: int) -> Optional[DepartmentEntity]: ...
    def create(self, organization_id: int, name: str, description: Optional[str]) -> DepartmentEntity: ...
    def save(self, dept: DepartmentEntity) -> DepartmentEntity: ...
    def list_memberships_by_department(self, department_id: int, organization_id: int) -> list[DepartmentMembershipEntity]: ...
    def list_active_memberships_by_user(self, user_id: int, organization_id: int) -> list[DepartmentMembershipEntity]: ...
    def deactivate_user_memberships(self, user_id: int, organization_id: int, effective_to: date, exclude_department_id: Optional[int] = None) -> None: ...
    def ensure_active_membership(self, organization_id: int, department_id: int, user_id: int, effective_from: date) -> DepartmentMembershipEntity: ...


class AssetProvisioningPort(Protocol):
    def get_active_assignment_counts(self, ctx: RequestContext) -> dict[int, int]: ...
    def validate_available_assets(self, ctx: RequestContext, asset_ids: list[int]) -> list[int]: ...
    def assign_assets_to_user(self, ctx: RequestContext, user_id: int, asset_ids: list[int], reassign: bool = False) -> None: ...
    def create_and_assign_assets(self, ctx: RequestContext, assets: list[dict[str, Any]], user_lookup: dict[str, int]) -> tuple[int, int]: ...


class SubscriptionProvisioningPort(Protocol):
    def get_active_assignment_counts(self, ctx: RequestContext) -> dict[int, int]: ...
    def assign_subscriptions_to_user(self, ctx: RequestContext, user_id: int, subscription_ids: list[int]) -> None: ...
    def import_subscriptions(self, ctx: RequestContext, subscriptions: list[dict[str, Any]]) -> int: ...
    def ensure_subscription_and_assign(self, ctx: RequestContext, user_id: int, sub_name: str, plan: str, amount: Optional[float]) -> bool: ...


class LifecycleProvisioningPort(Protocol):
    def ensure_active_lifecycle(self, ctx: RequestContext, user_id: int, joined_at: date) -> None: ...


class IntegrationProvisioningPort(Protocol):
    def seed_connections(self, ctx: RequestContext, integrations: list[dict[str, Any]]) -> None: ...


class AuditEventPort(Protocol):
    def record(self, *, organization_id: int, actor_id: int, action: str, entity_type: str, entity_id: int, details: Optional[dict[str, Any]] = None) -> None: ...
