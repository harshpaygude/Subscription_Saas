"""Segregated domain ports (ISP/DIP) for Employee Lifecycle Service."""
from __future__ import annotations

from datetime import date
from typing import Any, Optional, Protocol

from unisora_kit import RequestContext
from app.domain.entities import EmployeeLifecycleEntity, LifecycleTaskEntity


class LifecycleRepository(Protocol):
    def get_by_id(self, lifecycle_id: int, organization_id: int) -> Optional[EmployeeLifecycleEntity]: ...
    def get_by_user(self, user_id: int, organization_id: int) -> Optional[EmployeeLifecycleEntity]: ...
    def list_by_org(self, organization_id: int) -> list[EmployeeLifecycleEntity]: ...
    def create(self, lifecycle: EmployeeLifecycleEntity) -> EmployeeLifecycleEntity: ...
    def save(self, lifecycle: EmployeeLifecycleEntity) -> EmployeeLifecycleEntity: ...


class LifecycleTaskRepository(Protocol):
    def get_by_id(self, task_id: int, organization_id: int) -> Optional[LifecycleTaskEntity]: ...
    def list_by_lifecycle(self, lifecycle_id: int) -> list[LifecycleTaskEntity]: ...
    def list_by_org(self, organization_id: int, *, status: Optional[str] = None) -> list[LifecycleTaskEntity]: ...
    def count_open_required(self, lifecycle_id: int) -> int: ...
    def find_open_by_related(
        self,
        lifecycle_id: int,
        task_type: str,
        *,
        subscription_assignment_id: Optional[int] = None,
        asset_assignment_id: Optional[int] = None,
    ) -> Optional[LifecycleTaskEntity]: ...
    def create(self, task: LifecycleTaskEntity) -> LifecycleTaskEntity: ...
    def save(self, task: LifecycleTaskEntity) -> LifecycleTaskEntity: ...


class IdentityPort(Protocol):
    def get_user(self, ctx: RequestContext, user_id: int) -> dict[str, Any]: ...
    def list_users(self, ctx: RequestContext) -> list[dict[str, Any]]: ...
    def list_departments(self, ctx: RequestContext) -> list[dict[str, Any]]: ...
    def sync_onboarding_membership(self, ctx: RequestContext, user_id: int, department_id: int, effective_from: date) -> None: ...
    def deactivate_memberships(self, ctx: RequestContext, user_id: int, effective_to: date) -> None: ...


class SubscriptionPort(Protocol):
    def subscription_exists(self, ctx: RequestContext, subscription_id: int) -> bool: ...
    def list_user_assignments(self, ctx: RequestContext, user_id: int, status: Optional[str] = None) -> list[dict[str, Any]]: ...
    def list_all_assignments(self, ctx: RequestContext) -> list[dict[str, Any]]: ...
    def get_assignment(self, ctx: RequestContext, assignment_id: int) -> Optional[dict[str, Any]]: ...


class AssetPort(Protocol):
    def get_asset(self, ctx: RequestContext, asset_id: int) -> Optional[dict[str, Any]]: ...
    def list_user_assignments(self, ctx: RequestContext, user_id: int, status: Optional[str] = None) -> list[dict[str, Any]]: ...
    def list_all_assignments(self, ctx: RequestContext) -> list[dict[str, Any]]: ...
    def get_assignment(self, ctx: RequestContext, assignment_id: int) -> Optional[dict[str, Any]]: ...


class AuditEventPort(Protocol):
    def record(self, *, organization_id: int, actor_id: int, action: str, entity_type: str, entity_id: int, details: Optional[dict[str, Any]] = None) -> None: ...
